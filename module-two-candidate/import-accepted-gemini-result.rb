require_relative 'bridge-server'
root=File.expand_path(__dir__)
data=File.join(root,'bridge-jobs')
marker=File.join(data,'accepted-gemini-reference-041629.json')
bridge=Bridge.new(mock:false,data:data)
if File.file?(marker)
  record=JSON.parse(File.read(marker));s=bridge.snapshot(record['id'])
  raise 'imported image changed' unless Digest::SHA256.file(File.join(data,s['id'],s['outputFilename'])).hexdigest==s['outputHash']
  puts JSON.generate(id:s['id'],state:s['state'],imported:false,modelCalls:0)
  exit
end
plan=JSON.parse(File.read(File.join(root,'reference-041629-v14-plan.json')))
DirectImagePlan.validate(plan)
reference=DirectImagePlan.image_part(plan,'reference')
input=plan.fetch('options').merge('imageBase64'=>reference['data'],'sourceHash'=>plan.dig('binding','sourceHash'),'budgetMicroUSD'=>260000)
s=bridge.freeze_direct(input)
raise 'accepted request binding changed' unless s['requestHash']==plan.dig('binding','requestHash')
raw=File.binread(File.join(root,'gemini-reference-041629-v14-one-call/response.json'))
result=GenerateContentAdapter.parse(200,raw,expected_dimensions:plan.dig('binding','expectedDimensions'))
bytes=result.delete('bytes')
File.binwrite(File.join(data,s['id'],result['outputFilename']),bytes)
s.merge!(result)
s.merge!('execution'=>'generic-generateContent','importedFrom'=>'accepted-single-gemini-test','finishedAt'=>Time.now.utc.iso8601,'visualAcceptance'=>'accepted-by-user')
bridge.atomic(File.join(data,s['id'],'state.json'),s)
bridge.atomic(File.join(data,s['id'],'user-feedback.json'),{'overallVisual'=>'accepted-by-user','note'=>'用户认可该真实 Gemini 结果；普通文案对应建议不阻碍使用。','at'=>Time.now.utc.iso8601})
ledger=bridge.generic_ledger(plan['binding'])
FileUtils.mkdir_p(ledger,mode:0700)
bridge.atomic(File.join(ledger,'binding.json'),plan['binding']) unless File.file?(File.join(ledger,'binding.json'))
bridge.atomic(marker,{'id'=>s['id'],'requestHash'=>s['requestHash'],'outputHash'=>s['outputHash'],'modelCalls'=>0})
puts JSON.generate(id:s['id'],state:s['state'],imported:true,modelCalls:0)
